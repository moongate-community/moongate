    private readonly uint[] _subkeys = new uint[40];
    private readonly uint[] _sboxKeys = new uint[2];

    public TwofishEngine(uint seed)
    {
        // POL reads the four network-order seed bytes into little-endian key words.
        var word = BinaryPrimitives.ReverseEndianness(seed);
        uint[] words = [word, word];
        _sboxKeys[0] = _sboxKeys[1] = EncodeRs(word, word);
        unchecked
        {
            for (uint i = 0; i < 20; i++)
            {
                var a = F32(i * 0x02020202, words);
                var b = BitOperations.RotateLeft(F32(i * 0x02020202 + 0x01010101, words), 8);
                _subkeys[2 * i] = a + b;
                _subkeys[2 * i + 1] = BitOperations.RotateLeft(a + 2 * b, 9);
            }
        }
    }

    internal void EncryptBlocks(Span<byte> data)
    {
        unchecked
        {
            for (var offset = 0; offset < data.Length; offset += 16)
            {
                var block = data.Slice(offset, 16);
                var a = BinaryPrimitives.ReadUInt32LittleEndian(block) ^ _subkeys[0];
                var b = BinaryPrimitives.ReadUInt32LittleEndian(block[4..]) ^ _subkeys[1];
                var c = BinaryPrimitives.ReadUInt32LittleEndian(block[8..]) ^ _subkeys[2];
                var d = BinaryPrimitives.ReadUInt32LittleEndian(block[12..]) ^ _subkeys[3];
                for (var round = 0; round < 16; round++)
                {
                    var t0 = F32(a, _sboxKeys);
                    var t1 = F32(BitOperations.RotateLeft(b, 8), _sboxKeys);
                    c = BitOperations.RotateRight(c ^ (t0 + t1 + _subkeys[8 + 2 * round]), 1);
                    d = BitOperations.RotateLeft(d, 1) ^ (t0 + 2 * t1 + _subkeys[9 + 2 * round]);
                    if (round < 15)
                    {
                        (a, c) = (c, a);
                        (b, d) = (d, b);
                    }
                }
                BinaryPrimitives.WriteUInt32LittleEndian(block, a ^ _subkeys[4]);
                BinaryPrimitives.WriteUInt32LittleEndian(block[4..], b ^ _subkeys[5]);
                BinaryPrimitives.WriteUInt32LittleEndian(block[8..], c ^ _subkeys[6]);
                BinaryPrimitives.WriteUInt32LittleEndian(block[12..], d ^ _subkeys[7]);
            }
        }
    }

    private static uint EncodeRs(uint k0, uint k1)
    {
        var r = k1;
        for (var i = 0; i < 8; i++)
        {
            if (i == 4)
            {
                r ^= k0;
            }
            var b = r >> 24;
            var g2 = ((b << 1) ^ ((b & 0x80) != 0 ? 0x14Du : 0)) & 0xFF;
            var g3 = (b >> 1) ^ ((b & 1) != 0 ? 0xA6u : 0) ^ g2;
            r = (r << 8) ^ (g3 << 24) ^ (g2 << 16) ^ (g3 << 8) ^ b;
        }
        return r;
    }

    private static uint F32(uint x, uint[] keys)
    {
        var k0 = keys[0];
        var k1 = keys[1];
        var a = Q1[Q0[Q0[(byte)x] ^ (byte)k1] ^ (byte)k0];
        var b = Q0[Q0[Q1[(byte)(x >> 8)] ^ (byte)(k1 >> 8)] ^ (byte)(k0 >> 8)];
        var c = Q1[Q1[Q0[(byte)(x >> 16)] ^ (byte)(k1 >> 16)] ^ (byte)(k0 >> 16)];
        var d = Q0[Q1[Q1[(byte)(x >> 24)] ^ (byte)(k1 >> 24)] ^ (byte)(k0 >> 24)];
        return (a ^ My(b) ^ Mx(c) ^ Mx(d)) |
               ((Mx(a) ^ My(b) ^ My(c) ^ d) << 8) |
               ((My(a) ^ Mx(b) ^ c ^ My(d)) << 16) |
               ((My(a) ^ b ^ My(c) ^ Mx(d)) << 24);
    }

    private static uint Lfsr1(uint x)
    {
        return (x >> 1) ^ ((x & 1) != 0 ? 0xB4u : 0);
    }
    private static uint Lfsr2(uint x)
    {
        return (x >> 2) ^ ((x & 2) != 0 ? 0xB4u : 0) ^ ((x & 1) != 0 ? 0x5Au : 0);
    }
    private static uint Mx(uint x)
    {
        return x ^ Lfsr2(x);
    }
    private static uint My(uint x)
    {
        return x ^ Lfsr1(x) ^ Lfsr2(x);
    }

